package panamagl.opengl;

import java.lang.foreign.MemorySegment;

/**
 * Resolve the native address of an OpenGL function at runtime.
 *
 * The bindings generated by jextract only declare as static functions the OpenGL functions declared
 * by the system headers. All other functions are declared by <code>glext.h</code> as function
 * pointer typedefs, for which jextract generates <code>PFN...PROC</code> classes. A {@link GL}
 * implementation invokes these functions through their <code>PFN...PROC</code> class, with the
 * address given by the {@link GLFunctionLoader} of the platform (see {@link AGL#load(String)}).
 *
 * <table border="1">
 * <caption>Static versus dynamic loading of OpenGL functions</caption>
 * <tr>
 * <th>OS</th>
 * <th>Static (bindings)</th>
 * <th>Dynamic (function loader)</th>
 * <th>Function loader</th>
 * </tr>
 * <tr>
 * <td>Windows</td>
 * <td>OpenGL 1.0 and 1.1, the only versions exported by <code>opengl32.dll</code></td>
 * <td>OpenGL 1.2 to 4.6 and extensions</td>
 * <td><code>wglGetProcAddress</code>, falling back on the symbols of <code>opengl32.dll</code>.
 * Requires a current GL context.</td>
 * </tr>
 * <tr>
 * <td>Linux</td>
 * <td>OpenGL 1.0 to 1.3, and <code>glBlendColor</code> / <code>glBlendEquation</code> of 1.4</td>
 * <td>OpenGL 1.4 to 4.6 and extensions</td>
 * <td><code>glXGetProcAddress</code></td>
 * </tr>
 * <tr>
 * <td>macOS</td>
 * <td>OpenGL 1.0 to 2.1, framebuffer objects of 3.0, sync and base vertex functions of 3.2</td>
 * <td>Other functions of OpenGL 3.0 to 3.3 (e.g. vertex array objects, transform feedback,
 * uniform buffers). They require a core profile context.</td>
 * <td>Symbols of the OpenGL framework loaded by <code>NativeLibLoader</code></td>
 * </tr>
 * </table>
 *
 * The {@link GL} interface covers OpenGL 1.0 to 3.3. The Windows and Linux implementations also
 * provide OpenGL 4.x functions, the macOS one does not.
 *
 * A function that can not be resolved, because the driver does not provide it or no context is
 * current, makes the {@link GL} method throw an {@link UnsupportedOperationException}.
 *
 * @see AGL#load(String)
 *
 * @author Martin Pernollet
 */
public interface GLFunctionLoader {
  /**
   * Return the address of the given OpenGL function, or {@link MemorySegment#NULL} if the function
   * can not be resolved.
   */
  MemorySegment getProcAddress(String function);
}
